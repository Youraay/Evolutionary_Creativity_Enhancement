"""Preparation of the Think-Then-Generate experiment (T2G, https://github.com/SJTU-DENG-Lab/Think-Then-Generate).

Rewrites the prompts (reasoning + "Revised Prompt") exactly as ``inference.py`` of the T2G repository: the
Qwen2.5-VL language model of the T2G pipeline, the same system prompt, greedy decoding (``do_sample=False``),
``max_new_tokens=1024``.

    python -m experiments.think_then_generate.rewrite_prompts --out <dir>

Output: ``rewrites.json`` / ``rewrites.tsv``. The rewrites used by the worker are stored in
``data/prompts/t2g_rewritten_prompts.json``.
"""
import argparse
import json
import re
import time
from pathlib import Path

import pandas as pd
import torch

from experiments.common.settings import HF_CACHE

MODEL = "SJTU-DENG-Lab/Think-Then-Generate-T2I"
CLIP_TOKENIZER = "openai/clip-vit-base-patch32"
"""Same BPE as the SDXL text encoders (77 tokens); used to count the tokens of the rewrites."""

# Verbatim copy from inference.py of the T2G repository.
SYSTEM_PROMPT = """You are a Prompt Optimizer specializing in image generation models (e.g., MidJourney, Stable Diffusion). Your core task is to rewrite user-provided prompts into highly clear, easy-to-render versions.
When rewriting, prioritize the following principles:
1. Start from the user's prompt, do reasoning step by step to analyze the object or scene they want to generate.
2. Focus on describing the final visual appearance of the scene. Clarify elements like the main subject’s shape, color, and state.
3. If you are confident about what the user wants to generate, directly point it out in your explanation and the final revised prompt.
4. If technical concepts are necessary but difficult for ordinary users to understand, translate them into intuitive visual descriptions.
5. Ensure the final revised prompt is consistent with the user's intent.

After receiving the user’s prompt that needs rewriting, first explain your reasoning for optimization. Then, output the final revised prompt in the fixed format of "Revised Prompt:\n". Where the specific revised content is filled in the next line.

""" + "Prompt: \n"   # the trailing space is part of the original

PROMPTS = [
    # standard prompts and variants
    "a cat", "a creative cat", "a novel cat", "an unusual cat",
    "a chair", "a creative chair", "a novel chair", "an unusual chair",
    "boredom", "a creative depiction of boredom", "creativity",
    "a dog", "a coffee mug",
    # PartiPrompts from several challenges
    "commonsense",
    "The collision of two black holes in the center of a galaxy.",
    "Pneumonoultramicroscopicsilicovolcanoconiosis",
    "Oil painting generated by artificial intelligence",
    "The Starry Night",
    "a green pepper to the left of a red pepper",
    "a red cube on top of a blue cube",
]


def extract_prompt(text: str) -> str:
    """Return the text after ``"Revised Prompt:"`` (as ``inference.py``), or the whole text if it is missing.

    Args:
        text: Output of the language model.

    Returns:
        The revised prompt.
    """
    match = re.search(r"Revised Prompt:\n(.*)", text, re.DOTALL) or re.search(r"Revised Prompt:(.*)", text, re.DOTALL)
    return match.group(1).strip() if match else text.strip()


def rewrite(text_encoder, tokenizer, prompts: list[str], device: str) -> list[dict]:
    """Rewrite prompts with the T2G language model (greedy decoding).

    Args:
        text_encoder: Qwen2.5-VL language model of the T2G pipeline.
        tokenizer: Its tokenizer (with chat template).
        prompts: Prompts to rewrite.
        device: Device of the model.

    Returns:
        One dict per prompt with the revised prompt, the reasoning, token counts and run time.
    """
    from transformers import CLIPTokenizer

    clip_tokenizer = CLIPTokenizer.from_pretrained(CLIP_TOKENIZER, cache_dir=HF_CACHE)
    rows = []
    for prompt in prompts:
        messages = [{"role": "user", "content": SYSTEM_PROMPT + prompt}]
        text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        inputs = tokenizer([text], return_tensors="pt", padding=True).to(device)
        start = time.time()
        with torch.inference_mode():
            output_ids = text_encoder.generate(**inputs, do_sample=False, max_new_tokens=1024)
        seconds = time.time() - start
        new_tokens = output_ids[0, inputs.input_ids.shape[1]:]
        output = tokenizer.decode(new_tokens, skip_special_tokens=True, clean_up_tokenization_spaces=False)
        revised = extract_prompt(output)
        rows.append({
            "prompt": prompt, "revised_prompt": revised, "reasoning": output.split("Revised Prompt:")[0].strip(),
            "found_marker": "Revised Prompt:" in output,
            "revised_words": len(revised.split()),
            "revised_clip_tokens": len(clip_tokenizer(revised).input_ids),    # incl. BOS/EOS; SDXL truncates at 77
            "generated_tokens": int(len(new_tokens)), "seconds": round(seconds, 1),
        })
        print(f"[REWRITE] {prompt!r} -> {len(revised.split())} words, {rows[-1]['revised_clip_tokens']} CLIP tokens, "
              f"{seconds:.0f}s\n          {revised}", flush=True)
    return rows


def main() -> None:
    """Rewrite the prompts."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    device = "cuda"

    from diffusers import QwenImagePipeline

    start = time.time()
    pipe = QwenImagePipeline.from_pretrained(MODEL, cache_dir=HF_CACHE, torch_dtype=torch.bfloat16).to(device)
    pipe.set_progress_bar_config(disable=True)
    tokenizer = pipe.tokenizer          # Qwen2Tokenizer with chat template (no AutoTokenizer: the repo has no config.json)
    print(f"[INFO] Pipeline loaded in {time.time() - start:.0f}s, VRAM {torch.cuda.memory_allocated() / 2**30:.1f} GB",
          flush=True)

    rows = rewrite(pipe.text_encoder, tokenizer, PROMPTS, device)
    (args.out / "rewrites.json").write_text(json.dumps(rows, indent=2, ensure_ascii=False))
    pd.DataFrame(rows).to_csv(args.out / "rewrites.tsv", sep="\t", index=False)
    print("[INFO] done", flush=True)


if __name__ == "__main__":
    main()
